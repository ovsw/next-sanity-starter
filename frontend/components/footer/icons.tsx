export type FooterIconName = keyof typeof paths;

export function FooterIcon({
  className,
  name,
}: {
  className?: string;
  name: FooterIconName;
}) {
  return (
    <svg aria-hidden className={className} fill="currentColor" viewBox="0 0 24 24">
      <path d={paths[name]} />
    </svg>
  );
}

const socialHosts: Array<[FooterIconName, string[]]> = [
  ["youtube", ["youtube.com", "youtu.be"]],
  ["x", ["twitter.com", "x.com"]],
  ["linkedin", ["linkedin.com"]],
  ["facebook", ["facebook.com", "fb.com"]],
  ["instagram", ["instagram.com"]],
  ["pin", ["maps.google.com", "maps.app.goo.gl"]],
];

// Maps an external link to its social glyph; returns null for internal or
// unrecognized destinations so those keep rendering as plain text links.
export function socialIconFor(href: string): FooterIconName | null {
  let url: URL;
  try {
    url = new URL(href);
  } catch {
    return null;
  }
  const host = url.hostname.replace(/^www\./, "");
  for (const [name, hosts] of socialHosts) {
    if (hosts.some((h) => host === h || host.endsWith(`.${h}`))) return name;
  }
  if (host === "google.com" && url.pathname.startsWith("/maps")) return "pin";
  return null;
}
