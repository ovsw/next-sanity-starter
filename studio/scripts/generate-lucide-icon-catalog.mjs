import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";
import { dynamicIconImports } from "lucide-react/dynamic.mjs";

const require = createRequire(import.meta.url);
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const catalogOutputPath = path.resolve(
  scriptDirectory,
  "../schemas/inputs/lucide-icon-names.ts",
);

async function getLucidePaths() {
  const packagePath = require.resolve("lucide-react/package.json");
  const packageDirectory = path.dirname(packagePath);
  const packageJson = JSON.parse(await readFile(packagePath, "utf8"));

  return {
    iconsDirectory: path.join(packageDirectory, "dist/esm/icons"),
    version: packageJson.version,
  };
}

export async function getCanonicalLucideIconNames() {
  const { iconsDirectory } = await getLucidePaths();
  const iconFiles = (await readdir(iconsDirectory))
    .filter((filename) => filename.endsWith(".mjs") && filename !== "index.mjs")
    .sort();
  const canonicalNames = [];

  for (const filename of iconFiles) {
    const source = await readFile(path.join(iconsDirectory, filename), "utf8");

    // Lucide ships legacy aliases as tiny modules that only re-export the
    // canonical icon. Keeping those out prevents duplicate picker entries.
    if (source.includes("export { default } from")) continue;
    canonicalNames.push(filename.slice(0, -4));
  }

  return canonicalNames;
}

export async function buildLucideIconCatalog() {
  const { version } = await getLucidePaths();
  const names = await getCanonicalLucideIconNames();

  return `// Generated by studio/scripts/generate-lucide-icon-catalog.mjs.\n// Lucide React ${version}; do not edit by hand.\n\nexport const lucideIconNames = ${JSON.stringify(names, null, 2)} as const;\n`;
}

export async function getLucideIconAliases() {
  const canonicalNames = new Set(await getCanonicalLucideIconNames());
  return Object.keys(dynamicIconImports)
    .filter((name) => !canonicalNames.has(name))
    .sort();
}

async function run() {
  await writeFile(catalogOutputPath, await buildLucideIconCatalog());
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  run().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
